package com.filestorage.adapter.out.search.document;

import com.fasterxml.jackson.annotation.JsonIgnoreProperties;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.springframework.data.annotation.Id;
import org.springframework.data.elasticsearch.annotations.DateFormat;
import org.springframework.data.elasticsearch.annotations.Document;
import org.springframework.data.elasticsearch.annotations.Field;
import org.springframework.data.elasticsearch.annotations.FieldType;
import org.springframework.data.elasticsearch.annotations.InnerField;
import org.springframework.data.elasticsearch.annotations.MultiField;

import java.time.Instant;
import java.util.UUID;

/**
 * Elasticsearch document for a {@code File}.
 *
 * <p>{@code originalName} is a {@link MultiField} — primary {@code text} field
 * for fuzzy full-text match, plus a {@code search_as_you_type} sub-field
 * {@code originalName.sayt} (with {@code _2gram} / {@code _3gram} children
 * automatically generated by ES) used exclusively by the SAYT endpoint.
 *
 * <p>{@code content} is plain {@code text} — deliberately NOT included in SAYT
 * so the dropdown stays fast and the index stays small. It is always excluded
 * from {@code _source} on responses; only highlight snippets reach the client.
 *
 * <p>There is intentionally no {@code status} field — the existence of the
 * document IS the status. We create the document on ACTIVE transition and
 * delete it on physical removal.
 *
 * <p>The index name is read from {@code app.elasticsearch.indices.files} so
 * the same image can target {@code files}, {@code files-staging}, etc.
 */
@Document(indexName = "#{@elasticsearchProperties.indices.files}", createIndex = false)
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
@JsonIgnoreProperties(ignoreUnknown = true)
public class FileDocument {

    @Id
    private String id;

    @Field(type = FieldType.Keyword)
    private String tenantId;

    @Field(type = FieldType.Keyword)
    private String folderId;

    @Field(type = FieldType.Keyword)
    private String uploadedBy;

    @MultiField(
            mainField = @Field(type = FieldType.Text, analyzer = "icu_analyzer"),
            otherFields = {
                    @InnerField(suffix = "sayt", type = FieldType.Search_As_You_Type)
            }
    )
    private String originalName;

    @Field(type = FieldType.Keyword)
    private String mimeType;

    /** Extracted plain text. Absent for non-extractable MIME types. */
    @Field(type = FieldType.Text, analyzer = "icu_analyzer")
    private String content;

    @Field(type = FieldType.Date, format = DateFormat.date_time)
    private Instant createdAt;

    public static String idOf(UUID fileId) {
        return fileId.toString();
    }
}
