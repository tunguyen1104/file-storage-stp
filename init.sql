CREATE EXTENSION IF NOT EXISTS ltree;

CREATE TYPE "permission_file" AS ENUM (
  'VIEW',
  'EDIT',
  'MANAGE'
);

CREATE TABLE "tenants" (
  "id" uuid PRIMARY KEY,
  "name" varchar(255) NOT NULL,
  "slug" varchar(100) UNIQUE NOT NULL,
  "storage_quota_bytes" bigint NOT NULL DEFAULT 53687091200,
  "storage_used_bytes" bigint NOT NULL DEFAULT 0,
  "is_active" boolean NOT NULL DEFAULT true,
  "created_by" uuid,
  "created_at" timestamptz NOT NULL DEFAULT (now()),
  "updated_at" timestamptz NOT NULL DEFAULT (now())
);

CREATE TABLE "users" (
  "id" uuid PRIMARY KEY,
  "tenant_id" uuid NOT NULL,
  "email" varchar(255) UNIQUE NOT NULL,
  "password_hash" varchar(255) NOT NULL,
  "full_name" varchar(255) NOT NULL,
  "role_id" uuid NOT NULL,
  "is_active" boolean NOT NULL DEFAULT true,
  "storage_quota_bytes" bigint NOT NULL DEFAULT 10737418240,
  "storage_used_bytes" bigint NOT NULL DEFAULT 0,
  "created_by" uuid NOT NULL,
  "last_login_at" timestamptz,
  "password_changed_at" timestamptz NOT NULL DEFAULT (now()),
  "created_at" timestamptz NOT NULL DEFAULT (now()),
  "updated_at" timestamptz NOT NULL DEFAULT (now())
);

CREATE TABLE "refresh_tokens" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "user_id" uuid NOT NULL,
  "token" uuid UNIQUE NOT NULL,
  "expiry_at" timestamptz NOT NULL,
  "ipv4_address" varchar(45),
  "device_info" varchar(255),
  "created_at" timestamptz NOT NULL,
  "updated_at" timestamptz
);

CREATE TABLE "roles" (
  "id" uuid PRIMARY KEY,
  "code" varchar(50) UNIQUE NOT NULL,
  "name" varchar(100) UNIQUE NOT NULL,
  "description" text,
  "created_at" timestamptz NOT NULL DEFAULT (now()),
  "updated_at" timestamptz NOT NULL DEFAULT (now())
);

CREATE TABLE "folders" (
  "id" uuid PRIMARY KEY,
  "tenant_id" uuid NOT NULL,
  "parent_id" uuid,
  "owner_id" uuid,
  "name" varchar(255) NOT NULL,
  "path" ltree NOT NULL,
  "created_by" uuid NOT NULL,
  "created_at" timestamptz NOT NULL DEFAULT (now()),
  "updated_at" timestamptz NOT NULL DEFAULT (now())
);

CREATE TABLE "files" (
  "id" uuid PRIMARY KEY,
  "folder_id" uuid,
  "tenant_id" uuid NOT NULL,
  "uploaded_by" uuid NOT NULL,
  "original_name" varchar(500) NOT NULL,
  "storage_key" varchar(1000) NOT NULL,
  "mime_type" varchar(100),
  "size_bytes" bigint NOT NULL,
  "checksum_md5" varchar(32),
  "status" varchar(20) NOT NULL DEFAULT 'ACTIVE',
  "deleted_at" timestamptz,
  "scheduled_delete_at" timestamptz,
  "thumbnail_key" varchar(1000),
  "is_indexed" boolean NOT NULL DEFAULT false,
  "created_at" timestamptz NOT NULL DEFAULT (now()),
  "updated_at" timestamptz NOT NULL DEFAULT (now())
);

CREATE TABLE "multipart_upload_sessions" (
  "upload_id" varchar(255) PRIMARY KEY,
  "file_id" uuid NOT NULL,
  "tenant_id" uuid NOT NULL,
  "initiated_by" uuid NOT NULL,
  "object_key" varchar(1000) NOT NULL,
  "original_name" varchar(500) NOT NULL,
  "mime_type" varchar(100),
  "total_size_bytes" bigint NOT NULL,
  "total_parts" integer NOT NULL,
  "uploaded_parts" jsonb NOT NULL DEFAULT ('[]'),
  "status" varchar(20) NOT NULL DEFAULT 'IN_PROGRESS',
  "expires_at" timestamptz NOT NULL,
  "created_at" timestamptz NOT NULL DEFAULT (now())
);

CREATE TABLE "audit_logs" (
  "id" uuid PRIMARY KEY,
  "tenant_id" uuid NOT NULL,
  "user_id" uuid,
  "file_id" uuid,
  "action" varchar(50) NOT NULL,
  "ip_address" inet,
  "user_agent" text,
  "extra_data" jsonb,
  "created_at" timestamptz NOT NULL DEFAULT (now())
);

CREATE TABLE "file_shares" (
  "id" uuid PRIMARY KEY,
  "tenant_id" uuid NOT NULL,
  "file_id" uuid,
  "folder_id" uuid,
  "shared_with_user_id" uuid,
  "shared_with_tenant_id" uuid,
  "permission" permission_file NOT NULL DEFAULT 'VIEW',
  "shared_by" uuid NOT NULL,
  "expires_at" timestamptz,
  "created_at" timestamptz NOT NULL DEFAULT (now())
);

CREATE INDEX "idx_users_tenant_id" ON "users" ("tenant_id");

